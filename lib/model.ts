// Token Radar model, version radar-2.
//
// One snapshot in, one ranked board out. The board ranks every
// pre-token protocol the snapshot carries: the 40-protocol watchlist
// is the floor, and every other rankable pre-token protocol below
// that floor joins it, so the radar covers the whole pre-token
// universe instead of a capped sample.
//
// Implied value is a comparables model, computed from the snapshot
// itself at run time, never from a list of names:
//
//   category multiple = the median market-cap / TVL of the live-token
//     protocols in the same category, each ratio capped at 2x, shrunk
//     toward the global median with a prior of 3, and clamped to
//     [0.05, 1.00]; a category with no live protocol falls back to
//     the global median.
//   growth multiplier = 1 + clamp(change_7d, -60, 120) / 100 * 0.5
//   maturity multiplier = 0.60 + min(age_days, 1095) / 1095 * 0.40,
//     where age_days is the time since DefiLlama first listed the
//     protocol, or 365 days when it is not listed.
//   chain multiplier = 1 + 0.05 * (chains - 1), capped at 1.20.
//   implied = round(tvl_usd * category * growth * maturity * chains)
//
// A protocol is pre-token when its record carries no market cap, no
// CoinGecko id and no symbol. Live-token protocols are never ranked:
// their market cap is a fact, and the dashboard shows it beside the
// board instead of mixing it into the ranking.

/** One protocol as the sealed snapshot carries it. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

